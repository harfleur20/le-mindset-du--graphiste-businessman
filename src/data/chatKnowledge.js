const normalize = (value) =>
  value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

export const getRelevantKnowledge = (message, limit = 4) => {
  const normalizedMessage = normalize(message);

  return CHAT_KNOWLEDGE
    .map((entry) => {
      const score = entry.keywords.reduce((total, keyword) => {
        return normalizedMessage.includes(normalize(keyword)) ? total + 1 : total;
      }, 0);

      return { ...entry, score };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(({ title, content }) => `## ${title}\n${content.trim()}`)
    .join("\n\n");
};
